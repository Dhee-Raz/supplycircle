import assert from 'node:assert/strict';
const base = process.argv[2] || 'http://127.0.0.1:5173';
if (!['localhost','127.0.0.1'].includes(new URL(base).hostname)) throw new Error('Use a disposable local server.');
const suffix = Date.now();
function client(label) {
 let cookie = '';
 const identifier = `${label}_${suffix}@example.test`;
 return {identifier, async call(body, path='/api/data') {
  const response = await fetch(base+path, {method:body?'POST':'GET',headers:{Cookie:cookie,...(body?{'Content-Type':'application/json'}:{})},body:body?JSON.stringify(body):undefined});
  if(response.headers.has('set-cookie')) cookie=response.headers.get('set-cookie').split(';')[0];
  return {status:response.status,data:await response.json()};
 }, async signup() {assert.equal((await this.call({action:'signup',identifier,username:`${label}_${suffix}`,name:label,password:'team management test password'},'/api/auth')).status,200);} };
}
const owner=client('teamowner'),employee=client('teammember'),outsider=client('teamother');
for(const user of [owner,employee,outsider]) await user.signup();
for(const user of [owner,outsider]) assert.equal((await user.call({action:'setup',business:'Team management verification',store:'Test store'})).status,200);
let state=(await owner.call()).data;
const storeId=state.stores[0].id;
const invitation={action:'invite',identifier:employee.identifier,name:'Employee',role:'employee',storeId};
let result=await owner.call(invitation);
assert.equal(result.status,200);
assert.equal(result.data.delivery.status,'not_configured','Run without messaging credentials to avoid real sends');
const oldToken=new URL(result.data.inviteUrl).hash.slice(8);
state=(await owner.call()).data;
const id=state.invitations[0].id;
assert.equal((await outsider.call({...invitation,action:'editInvitation',id})).status,404);
result=await owner.call({...invitation,action:'editInvitation',id,name:'Updated invite'});
assert.equal(result.status,200);
assert.equal((await employee.call({action:'join',token:oldToken})).status,400);
assert.equal((await employee.call({action:'join',token:new URL(result.data.inviteUrl).hash.slice(8)})).status,200);
assert.equal((await employee.call({action:'deleteMember',identifier:owner.identifier})).status,403);
assert.equal((await outsider.call({action:'deleteMember',identifier:employee.identifier})).status,404);
assert.equal((await owner.call({action:'deleteMember',identifier:owner.identifier})).status,403);
assert.equal((await owner.call({action:'editMember',identifier:employee.identifier,name:'Updated member',role:'employee',storeId:'wrong-store'})).status,400);
// Employee permissions must hold even when requests bypass the interface.
assert.equal((await owner.call({action:'addStore',name:'Other store'})).status,200);
const otherStore=(await owner.call()).data.stores.find(store=>store.id!==storeId).id;
const fields={name:'Stock permission check',quantity:2,unit:'pieces',category:'Other',priority:'normal',note:''};
assert.equal((await employee.call({action:'addItem',store:otherStore,...fields})).status,403);
assert.equal((await employee.call({action:'addItem',store:storeId,...fields})).status,200);
let employeeState=(await employee.call()).data;
assert.deepEqual(employeeState.stores.map(store=>store.id),[storeId]);
const requestId=employeeState.items[0].id;
assert.equal((await employee.call({action:'editItem',id:requestId,...fields,name:'Edited request'})).status,200);
assert.equal((await employee.call({action:'editItem',id:requestId,store:otherStore,...fields})).status,403);
for(const action of ['deleteItem','claim','order','receive','buy','reopen','addStore','invite']) assert.equal((await employee.call({action,id:requestId,...fields})).status,403,action);
assert.equal((await owner.call({action:'addItem',store:storeId,...fields,name:'Owner request'})).status,200);
const ownerRequest=(await owner.call()).data.items.find(item=>item.name==='Owner request').id;
